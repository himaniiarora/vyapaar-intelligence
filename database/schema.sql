-- <=> vector ke beech distance/similarity calculate karta hai.
create or replace function match_memories (
  query_embedding extensions.vector(384),
  match_threshold float,
  match_count int
)
returns table (
  id bigint,
  content text,
  memory_type text,
  source_interaction_ids bigint[],
  similarity float
)
language sql
as $$
  select
    m.id,
    m.content,
    m.memory_type,
    m.source_interaction_ids,
    1 - (m.embedding <=> query_embedding) as similarity
  from memories m
  where 1 - (m.embedding <=> query_embedding) >= match_threshold
  order by m.embedding <=> query_embedding
  limit match_count;
$$;


-- Backend ko permission do ki woh ye search function chala sake.
grant execute on function match_memories(extensions.vector(384), float, int)
to service_role;