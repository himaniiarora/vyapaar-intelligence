import os
from fastapi import FastAPI
from supabase import create_client
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from dotenv import load_dotenv
from supabase import create_client
from sentence_transformers import SentenceTransformer
from ollama import chat
import pandas as pd

# Load environment variables
load_dotenv()

url = os.getenv("SUPABASE_URL")
key = os.getenv("SUPABASE_KEY")

supabase = create_client(url, key)


# Embedding model
embedding_model = SentenceTransformer(
    "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
)


app = FastAPI()


# Allow frontend to talk to backend
app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:3000"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


class Question(BaseModel):
    question: str


@app.get("/")
def home():
    return {"message": "Vyapaar Intelligence backend is running!"}


@app.get("/dashboard")
def dashboard():

    # Get all customer interactions
    response = supabase.table("interactions").select("*").execute()

    interactions = response.data
    df = pd.DataFrame(interactions)

    recent_interactions = (
        df.sort_values("created_at", ascending=False)[
            ["platform", "customer_name", "message", "product", "interaction_type"]
        ]
        .head(5)
        .to_dict("records")
    )

    # Product demand
    product_demand = df["product"].value_counts().to_dict()

    df["created_at"] = pd.to_datetime(df["created_at"])

    demand_trends = (
        df.groupby(df["created_at"].dt.strftime("%Y-%m-%d"))["product"]
        .count()
        .to_dict()
    )

    # Interaction types
    interaction_types = df["interaction_type"].value_counts().to_dict()

    # Platform activity
    platform_activity = df["platform"].value_counts().to_dict()

    # Purchase interest
    purchase_interest = df[df["interaction_type"] == "purchase_interest"][
        ["customer_name", "product", "message"]
    ].to_dict("records")

    # Complaints
    complaints = df[df["interaction_type"] == "complaint"][
        ["customer_name", "product", "message"]
    ].to_dict("records")

    # Business memories generated by Gemma
    memory_response = (
        supabase.table("memories")
        .select("content")
        .eq("memory_type", "business_pattern")
        .execute()
    )

    business_memories = memory_response.data
    
    memory_count_response = (
        supabase
        .table("memories")
        .select("id", count="exact")
        .execute()
    )

    memory_count = memory_count_response.count or 0

    return {
        "product_demand": product_demand,
        "interaction_types": interaction_types,
        "platform_activity": platform_activity,
        "purchase_interest": purchase_interest,
        "complaints": complaints,
        "business_memories": business_memories,
        "demand_trends": demand_trends,
        "recent_interactions": recent_interactions,
        "memory_count": memory_count,
    }


@app.post("/ask")
def ask_vyapaar(data: Question):

    # --------------------------------
    # 1. GET BUSINESS INTERACTIONS
    # --------------------------------

    response = supabase.table("interactions").select("*").execute()

    df = pd.DataFrame(response.data)

    # --------------------------------
    # 2. BUSINESS SIGNALS
    # --------------------------------

    product_demand = df["product"].value_counts().to_dict()

    interaction_types = df["interaction_type"].value_counts().to_dict()

    platform_activity = df["platform"].value_counts().to_dict()

    purchase_df = df[df["interaction_type"] == "purchase_interest"]

    purchase_interest = purchase_df[["customer_name", "product", "message"]].to_dict(
        "records"
    )

    # --------------------------------
    # 3. SEARCH BUSINESS MEMORY
    # --------------------------------

    question = data.question

    query_embedding = embedding_model.encode(question).tolist()

    search_response = supabase.rpc(
        "match_memories",
        {"query_embedding": query_embedding, "match_threshold": 0.3, "match_count": 8},
    ).execute()

    memories = search_response.data

    # --------------------------------
    # 4. BUILD AI CONTEXT
    # --------------------------------

    context = f"""
You are Vyapaar Intelligence, an AI business
assistant for small business owners.

BUSINESS SIGNALS

Product demand:
{product_demand}

Interaction types:
{interaction_types}

Platform activity:
{platform_activity}

Purchase interest:
{purchase_interest}


BUSINESS MEMORY AND CUSTOMER CONTEXT:
"""

    for memory in memories:
        context += f"- {memory['content']}\n"

    # --------------------------------
    # 5. ASK GEMMA
    # --------------------------------

    prompt = f"""
You are Vyapaar Intelligence, a sharp and practical
business advisor for small Indian shopkeepers.

BUSINESS CONTEXT:
{context}

SHOPKEEPER'S QUESTION:
{question}

RESPONSE RULES:
1. Answer the exact question directly in 1-3 short sentences.
2. Use only relevant facts from the provided business context.
3. Never invent products, customer preferences, numbers,
   sales, complaints, or trends.
4. Interaction counts are not confirmed sales.
   Purchase interest is not a completed purchase.
5. Mention a specific product, size, or price only when
   supported by the available context.
6. If the requested information is unavailable, say so
   briefly and stop. Do not add unrelated advice.
7. Give one clear recommendation when the evidence supports it.
8. Do not repeat the question, add greetings, or use
   unnecessary introductions, headings, or conclusions.
9. LANGUAGE RULES:
    - If the question is in English, answer only in English.
    - If the question is in Hindi written in Devanagari,
     answer only in Hindi using Devanagari script.
    - If the question is in Hinglish written in Roman script,
     answer in Hinglish using Roman script.
    - Never answer a Hindi question in Hinglish.
    - Never answer a English question in Hindi.
    - Do not mix Hindi, English, and Romanized Hindi unnecessarily.
    - Keep the answer concise, relevant, and natural.
    - Use simple, everyday Hindi for Hindi questions.
10. Sound decisive, but never present an assumption as fact.

Write only the final answer.
"""

    gemma_response = chat(
        model="gemma4:e2b", 
        messages=[{"role": "user", "content": prompt}],
        keep_alive="10m",
    )

    answer = gemma_response.message.content

    # --------------------------------
    # 6. SEND ANSWER TO FRONTEND
    # --------------------------------

    return {"question": question, "answer": answer}